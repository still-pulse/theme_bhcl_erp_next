def to_csv_line(src: str, tgt: str) -> str:
	def esc(s: str) -> str:
		return '"' + s.replace('"', '""') + '"'

	return f"{esc(src)},{esc(tgt)}"

def main() -> None:
	seen: dict[str, str] = {}
	for src, tgt in TRANSLATIONS:
		seen[src] = tgt

	lines = [to_csv_line(s, t) for s, t in sorted(seen.items(), key=lambda x: x[0].lower())]
	base = Path(__file__).resolve().parents[1] / "bhcl_theme" / "translations"
	base.mkdir(parents=True, exist_ok=True)
	for name in ("pt-BR.csv", "pt.csv"):
		path = base / name
		path.write_text("\n".join(lines) + "\n", encoding="utf-8")
		print(f"Wrote {path} ({len(lines)} entries)")

if __name__ == "__main__":
	main()
