print("\n=== Missing translations (sample set) ===")
missing = []
for s in samples:
	t = _(s)
	if t == s:
		missing.append(s)
print(f"Missing: {len(missing)}/{len(samples)}")
for s in missing:
	print(" ", s)

print("\n=== Workspace labels ===")
labels = [doc.title]
labels += [s.label for s in (doc.shortcuts or []) if s.label]
labels += [l.label for l in (doc.links or []) if l.label]
for lab in labels:
	t = _(lab)
	mark = "OK" if t != lab else "EN"
	print(f" [{mark}] {lab!r} -> {t!r}")

print("\n=== Stock module DocTypes ===")
dts = frappe.get_all(
	"DocType",
	filters={"module": "Stock"},
	fields=["name"],
	order_by="name",
)
for d in dts:
	t = _(d.name)
	if t == d.name:
		print(" EN", d.name)
	else:
		print(" OK", d.name, "->", t)

print("\n=== Stock reports untranslated ===")
reps = frappe.get_all(
	"Report",
	filters={"module": "Stock", "disabled": 0},
	fields=["name", "report_name"],
	order_by="name",
)
for r in reps:
	for key in ("name", "report_name"):
		val = r.get(key)
		if not val:
			continue
		t = _(val)
		if t == val:
			print(" EN", val)

